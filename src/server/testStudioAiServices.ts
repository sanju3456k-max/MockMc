export const CANDIDATE_MODELS = [
  "gemini-flash-lite-latest",
  "gemini-3.1-flash-lite",
  "gemini-3.5-flash-lite",
  "gemini-3.8-flash",
  "gemini-flash-latest",
];

async function withTimeout<T>(promise: Promise<T>, timeoutMs = 25000, errorMsg = "Gemini request timed out"): Promise<T> {
  let timer: NodeJS.Timeout;
  const timeoutPromise = new Promise<never>((_, reject) => {
    timer = setTimeout(() => reject(new Error(errorMsg)), timeoutMs);
  });
  try {
    return await Promise.race([promise, timeoutPromise]);
  } finally {
    clearTimeout(timer!);
  }
}

export function getAiClient(): GoogleGenAI {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error("Gemini API key is not configured");
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

export async function generateWithFallback(ai: GoogleGenAI, params: { contents: any; config?: any }) {
  let lastErr: any = null;
  for (const model of CANDIDATE_MODELS) {
    try {
      const response = await withTimeout(
        ai.models.generateContent({
          model,
          contents: params.contents,
          config: params.config,
        }),
        25000,
        `Timed out querying ${model}`
      );
      if (response && response.text) {
        return response;
      }
    } catch (err: any) {
      lastErr = err;
      if (params.config?.tools) {
        try {
          const fallbackConfig = { ...params.config };
          delete fallbackConfig.tools;
          const fallbackRes = await withTimeout(
            ai.models.generateContent({
              model,
              contents: params.contents,
              config: fallbackConfig,
            }),
            20000,
            `Timed out querying ${model} without tools`
          );
          if (fallbackRes && fallbackRes.text) {
            return fallbackRes;
          }
        } catch (fErr) {
          lastErr = fErr;
        }
      }
      // If quota 429, 404, 503 or timeout, immediately continue to next candidate model
      continue;
    }
  }

  if (lastErr?.message?.includes("429") || lastErr?.message?.includes("RESOURCE_EXHAUSTED") || lastErr?.message?.includes("quota")) {
    return { text: "Notice: AI quota limit reached. Please try again shortly." };
  }

  throw lastErr || new Error("All candidate models failed during AI content generation.");
}

/**
 * Safely parses JSON generated by LLMs, repairing invalid LaTeX single backslashes
 * and stripping markdown wrappers.
 */
export function cleanAndParseJson(str: string): any {
  if (!str || typeof str !== 'string') return null;

  const trimmed = str.trim();

  // 1. Attempt direct parse
  try {
    return JSON.parse(trimmed);
  } catch (e) {
    // Proceed to repair
  }

  // 2. Strip markdown code block wrappers
  const stripped = trimmed
    .replace(/^```(?:json)?\s*/i, '')
    .replace(/\s*```$/, '')
    .trim();

  try {
    return JSON.parse(stripped);
  } catch (e) {
    // Proceed to repair unescaped backslashes inside string literals
  }

  // 3. Precise backslash repairing inside double-quoted strings
  let repaired = '';
  let inString = false;
  let isEscaped = false;

  for (let i = 0; i < stripped.length; i++) {
    const char = stripped[i];

    if (inString) {
      if (isEscaped) {
        isEscaped = false;
        repaired += char;
      } else if (char === '\\') {
        const nextChar = stripped[i + 1] || '';
        if (nextChar === '"' || nextChar === '\\' || nextChar === '/') {
          repaired += '\\';
          isEscaped = true;
        } else if (nextChar === 'u' && /^[0-9a-fA-F]{4}/.test(stripped.substring(i + 2, i + 6))) {
          repaired += '\\';
          isEscaped = true;
        } else if (['n', 'r', 't', 'b', 'f'].includes(nextChar)) {
          const followingChar = stripped[i + 2] || '';
          if (/^[a-zA-Z]/.test(followingChar)) {
            repaired += '\\\\';
          } else {
            repaired += '\\';
            isEscaped = true;
          }
        } else {
          repaired += '\\\\';
        }
      } else if (char === '"') {
        inString = false;
        repaired += char;
      } else if (char === '\n') {
        repaired += '\\n';
      } else if (char === '\r') {
        repaired += '\\r';
      } else if (char === '\t') {
        repaired += '\\t';
      } else {
        repaired += char;
      }
    } else {
      if (char === '"') {
        inString = true;
      }
      repaired += char;
    }
  }

  repaired = repaired.replace(/,\s*([\}\]])/g, '$1');

  try {
    return JSON.parse(repaired);
  } catch (e) {
    try {
      let aggressive = stripped
        .replace(/([^\\])\\([a-zA-Z0-9{}()_^+=\-*\/])/g, '$1\\\\$2')
        .replace(/,\s*([\}\]])/g, '$1')
        .replace(/([{,]\s*)([a-zA-Z0-9_$]+)\s*:/g, '$1"$2":')
        .replace(/'([^'\\]*(?:\\.[^'\\]*)*)'/g, '"$1"');
      return JSON.parse(aggressive);
    } catch {
      return null;
    }
  }
}

